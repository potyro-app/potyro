/** One icon, drawn the system's way. */
export function icon(Icon: LucideIcon, size: 16 | 20 | 24 = 20): ReactNode {
  return <Icon size={size} strokeWidth={2} absoluteStrokeWidth aria-hidden className="k-icon" />;
}

