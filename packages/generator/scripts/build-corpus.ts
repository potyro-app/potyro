// Regenerate `src/corpus.generated.ts` — the examples, personal apps, API docs and schema types the
// model can search and read (#262).
//
//   pnpm --filter @potyro/generator gen:corpus
//
// Committed, like the reference, so every backend and every build reads the same text without a
// build hook of its own. `test/corpus.test.ts` fails when it is stale.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildCorpus } from "../src/corpus.js";
import { collectCorpusFiles } from "../src/corpus-files.js";

const outFile = fileURLToPath(new URL("../src/corpus.generated.ts", import.meta.url));
const corpus = buildCorpus(collectCorpusFiles());

const header = [
  "// GENERATED by scripts/build-corpus.ts from examples/, apps/, docs/04-05 and packages/schema/src/types — do not edit.",
  "// Regenerate with `pnpm --filter @potyro/generator gen:corpus`; test/corpus.test.ts checks it is current.",
  "",
  'import type { Corpus } from "./corpus.js";',
  "",
].join("\n");

writeFileSync(outFile, `${header}\nexport const CORPUS: Corpus = ${JSON.stringify(corpus, null, 1)};\n`);
const chars = corpus.files.reduce((n, f) => n + f.text.length, 0);
console.log(`wrote ${outFile} (version ${corpus.version}, ${corpus.files.length} files, ${chars} chars)`);
