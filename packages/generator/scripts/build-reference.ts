// Regenerate `src/reference.generated.ts` from the schema's type declarations.
//
//   pnpm --filter @potyro/generator gen:reference
//
// Committed rather than built on the fly so the same text reaches every backend — Node evals, the
// browser Studio, the CLI — without a build hook in each. `test/reference.test.ts` fails when this
// is stale, which is the whole point: the prompt cannot say less than the schema does.
//
// Two exports since #341: the CORE every system prompt carries, and each capability's declarations,
// read through `lookup` and the passages beside a request (src/reference.ts `CAPABILITIES`).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { splitReference } from "../src/reference.js";
import { readReferenceSources } from "../src/reference-files.js";

const outFile = fileURLToPath(new URL("../src/reference.generated.ts", import.meta.url));

const { core, lookupOnly } = readReferenceSources();
const split = splitReference(core, lookupOnly);

const header = [
  "// GENERATED by scripts/build-reference.ts from packages/schema/src/types — do not edit.",
  "// Regenerate with `pnpm --filter @potyro/generator gen:reference`; test/reference.test.ts checks it is current.",
  "",
  "/** The core of the `potyro` module's type declarations, verbatim: what every system prompt carries. */",
].join("\n");

const body = [
  `${header}\nexport const SCHEMA_REFERENCE: string = ${JSON.stringify(split.core)};`,
  "",
  "/** Each capability's declarations (src/reference.ts `CAPABILITIES`), verbatim: read through `lookup` and `capabilityNotes`. */",
  `export const CAPABILITY_REFERENCE: Readonly<Record<string, string>> = ${JSON.stringify(split.capabilities, null, 2)};`,
  "",
].join("\n");

writeFileSync(outFile, body);
const moved = Object.values(split.capabilities).reduce((n, t) => n + t.length, 0);
console.log(`wrote ${outFile} (core ${split.core.length} chars; ${Object.keys(split.capabilities).length} capabilities, ${moved} chars, read on demand)`);
