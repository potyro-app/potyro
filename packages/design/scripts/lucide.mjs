// Every Lucide icon as ONE path, by its name (DESIGN.md §3.5: an app's icons are Lucide, drawn with
// the stroke of the logo). An app names an icon ("shopping-cart"); the shell draws it in a tab bar, a
// tile, a row's lead, the share image's canvas — so the data has to serve <svg> and Path2D alike, and
// a single `d` string does both. The source is the `lucide` data package (icons as [tag, attrs][]);
// circles, rects, lines and polylines are rewritten as path commands here, once.
//
//   node scripts/lucide.mjs    → src/lucide-paths.generated.ts (~2,170 icons; one lazy chunk)
//
// Re-run after bumping `lucide` in package.json. The names are the kebab-case ones on lucide.dev.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve("lucide/package.json")), "dist/esm/icons");
const version = require("lucide/package.json").version;

const n = (v) => Number(v);

/** A circle as two arcs. */
function circle({ cx, cy, r }) {
  const [x, y, R] = [n(cx), n(cy), n(r)];
  return `M${x - R} ${y}a${R} ${R} 0 1 0 ${2 * R} 0a${R} ${R} 0 1 0 ${-2 * R} 0`;
}

function ellipse({ cx, cy, rx, ry }) {
  const [x, y, RX, RY] = [n(cx), n(cy), n(rx), n(ry)];
  return `M${x - RX} ${y}a${RX} ${RY} 0 1 0 ${2 * RX} 0a${RX} ${RY} 0 1 0 ${-2 * RX} 0`;
}

/** A rect, with its rounded corners when it has them. */
function rect({ x = 0, y = 0, width, height, rx, ry }) {
  const [X, Y, W, H] = [n(x), n(y), n(width), n(height)];
  const RX = rx !== undefined ? n(rx) : ry !== undefined ? n(ry) : 0;
  const RY = ry !== undefined ? n(ry) : RX;
  if (!RX && !RY) return `M${X} ${Y}h${W}v${H}h${-W}z`;
  return (
    `M${X + RX} ${Y}h${W - 2 * RX}a${RX} ${RY} 0 0 1 ${RX} ${RY}v${H - 2 * RY}a${RX} ${RY} 0 0 1 ${-RX} ${RY}` +
    `h${-(W - 2 * RX)}a${RX} ${RY} 0 0 1 ${-RX} ${-RY}v${-(H - 2 * RY)}a${RX} ${RY} 0 0 1 ${RX} ${-RY}z`
  );
}

function line({ x1, y1, x2, y2 }) {
  return `M${n(x1)} ${n(y1)}L${n(x2)} ${n(y2)}`;
}

function poly(points, close) {
  const nums = String(points).trim().split(/[\s,]+/).map(Number);
  let d = "";
  for (let i = 0; i < nums.length; i += 2) d += `${i ? "L" : "M"}${nums[i]} ${nums[i + 1]}`;
  return close ? `${d}z` : d;
}

function toPath(nodes, name) {
  return nodes
    .map(([tag, attrs]) => {
      switch (tag) {
        case "path":
          return attrs.d;
        case "circle":
          return circle(attrs);
        case "ellipse":
          return ellipse(attrs);
        case "rect":
          return rect(attrs);
        case "line":
          return line(attrs);
        case "polyline":
          return poly(attrs.points, false);
        case "polygon":
          return poly(attrs.points, true);
        default:
          throw new Error(`${name}: unexpected <${tag}>`);
      }
    })
    .join("");
}

const names = readdirSync(iconsDir)
  .filter((f) => f.endsWith(".mjs") && f !== "index.mjs")
  .map((f) => f.slice(0, -4))
  .sort();

const out = {};
for (const name of names) {
  const mod = await import(pathToFileURL(join(iconsDir, `${name}.mjs`)).href);
  out[name] = toPath(mod.default, name);
}

// The old names Lucide still answers to ("edit" → "square-pen", "home" → "house"): a model that learnt
// them last year, or a person reading an older page, still gets the icon. The data package does not
// list them by kebab name; lucide-react's dynamic map does, alias → canonical file.
const reactDir = dirname(require.resolve("lucide-react/package.json"));
const dynamic = readFileSync(join(reactDir, "dist/esm/dynamicIconImports.mjs"), "utf8");
const aliases = {};
for (const [, alias, file] of dynamic.matchAll(/"([a-z0-9-]+)":\s*\(\)\s*=>\s*import\('\.\/icons\/([a-z0-9-]+)\.mjs'\)/g)) {
  if (alias !== file && out[file] && !out[alias]) aliases[alias] = file;
}

const lines = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const aliasLines = Object.entries(aliases)
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const src = `// GENERATED by scripts/lucide.mjs from lucide ${version} — do not edit. Every icon as one path in a
// 24×24 box, stroke 2, round caps and joins (DESIGN.md §3.5). Loaded lazily by src/lucide.ts.
export const LUCIDE_PATHS: Readonly<Record<string, string>> = {
${lines.join("\n")}
};

/** Lucide's older names, each to the icon it means today. */
export const LUCIDE_ALIASES: Readonly<Record<string, string>> = {
${aliasLines.join("\n")}
};
`;
writeFileSync(join(here, "../src/lucide-paths.generated.ts"), src);
console.log(`lucide ${version}: ${names.length} icons, ${aliasLines.length} aliases → src/lucide-paths.generated.ts`);
