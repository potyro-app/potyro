#!/usr/bin/env node
// Builds `dist/piano.app.tsx`, the ONE file the shell imports.
//
// The shell bundles an imported app from a single source string: `potyro` and `react` resolve, nothing
// else does. So this script inlines what `piano.app.tsx` imports from next door — `plan.json` as a
// constant, `plan.ts` and `progress.ts` as their source with the `export` keywords stripped — and
// writes the result. No esbuild: the output stays readable TypeScript, with comments and types, so
// the Studio's Source tab shows the same code that is in the repo.
//
//   node build.mjs            → dist/piano.app.tsx
//   node build.mjs --stdout   → the same, to stdout

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

/** Top-level `import … from "…";` statements, single- or multi-line. */
const IMPORT_RE = /^import\s[\s\S]*?\sfrom\s+"([^"]+)";[ \t]*\n?/gm;

/** A local module's source with its own imports dropped and its exports made plain declarations. */
function inlineModule(name, source) {
  const body = source.replace(IMPORT_RE, "").replace(/^export\s+(?=(?:async\s+)?(?:const|let|function|interface|type|class|enum)\b)/gm, "");
  if (/^export\s/m.test(body)) throw new Error(`${name}: an export this script cannot inline (only declarations are supported)`);
  return `// ---- inlined from ${name} ----\n${body.trim()}\n// ---- end ${name} ----\n`;
}

export async function build(dir = here) {
  const app = await readFile(join(dir, "piano.app.tsx"), "utf8");
  const modules = new Map();
  let inlinedAt = -1;

  let out = app.replace(IMPORT_RE, (stmt, spec) => {
    if (spec === "potyro" || spec === "react" || spec.startsWith("react/")) return stmt;
    // The plan is not code: it ships beside the app as a file (#253) and is read with ctx.files.
    if (spec.endsWith(".json")) throw new Error(`"${spec}": data ships as a file in the package, not inlined`);
    if (!spec.startsWith("./")) throw new Error(`cannot inline "${spec}"`);
    const name = spec.replace(/^\.\//, "").replace(/\.js$/, ".ts");
    modules.set(name, null);
    if (inlinedAt < 0) {
      inlinedAt = modules.size;
      return "/* __INLINED_MODULES__ */\n";
    }
    return "";
  });

  // Order by dependency: a module is placed after the ones it imports.
  const sources = new Map();
  for (const name of modules.keys()) sources.set(name, await readFile(join(dir, name), "utf8"));
  const ordered = [];
  const visit = (name) => {
    if (ordered.includes(name)) return;
    for (const m of sources.get(name).matchAll(IMPORT_RE)) {
      const dep = m[1].replace(/^\.\//, "").replace(/\.js$/, ".ts");
      if (sources.has(dep)) visit(dep);
    }
    ordered.push(name);
  };
  for (const name of sources.keys()) visit(name);

  const inlined = ordered.map((name) => inlineModule(name, sources.get(name))).join("\n");
  out = out.replace("/* __INLINED_MODULES__ */\n", inlined);
  const header = `// GENERATED by apps/piano/build.mjs from piano.app.tsx + ${ordered.join(" + ")}.\n// Do not edit: change the sources and rebuild (pnpm --filter @potyro/app-piano build).\n\n`;
  return header + out;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = await build();
  if (process.argv.includes("--stdout")) {
    process.stdout.write(text);
  } else {
    const target = join(here, "dist", "piano.app.tsx");
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, text);
    console.log(`wrote ${target} (${(text.length / 1024).toFixed(1)} kB)`);
    // The package Add an app installs: the built source, with plan.json shipped in the app's folder.
    const pack = fileURLToPath(new URL("../../scripts/pack-app.mjs", import.meta.url));
    execFileSync("node", [pack, target, join(here, "plan.json"), "-o", join(here, "dist", "piano.potyro-app.zip")], {
      stdio: "inherit",
      env: { ...process.env, INIT_CWD: here },
    });
  }
}
