#!/usr/bin/env node
// docs/README.md is generated from each doc's frontmatter, so the list of docs and what to trust
// cannot drift from the docs themselves.
//
//   node scripts/docs-index.mjs            write docs/README.md
//   node scripts/docs-index.mjs --check    exit 1 when it is stale or a doc has no frontmatter

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = join(ROOT, "docs");
const OUT = join(DOCS, "README.md");
const FILES = [
  ...readdirSync(DOCS).filter((n) => /^\d\d-.*\.md$|^handoff-.*\.md$/.test(n)),
  ...readdirSync(join(DOCS, "adr")).filter((n) => n.endsWith(".md")).map((n) => `adr/${n}`),
].sort();

function frontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(text);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^(\w+):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]] = kv[2].trim();
  }
  return out;
}

const missing = [];
const docs = [];
for (const file of FILES) {
  const fm = frontmatter(readFileSync(join(DOCS, file), "utf8"));
  if (!fm || !fm.title || !fm.status) {
    missing.push(file);
    continue;
  }
  // The owner's and the agents' working notes (`audience: owner`) stay in the private repository —
  // the public one is made without them (#115) — so the index the public reads does not name them.
  if (fm.audience === "owner") continue;
  docs.push({ file, ...fm, order: fm.order === undefined ? Infinity : Number(fm.order) });
}
if (missing.length) {
  for (const f of missing) console.error(`missing frontmatter: docs/${f}`);
  process.exit(1);
}

const current = docs.filter((d) => d.status === "current").sort((a, b) => a.order - b.order || a.file.localeCompare(b.file));
const historical = docs.filter((d) => d.status !== "current").sort((a, b) => a.file.localeCompare(b.file));
const line = (d) => `- [${d.title}](${d.file}) — ${d.description ?? ""}`.trimEnd();
const text = [
  "# Potyro documentation",
  "",
  "<!-- Generated by scripts/docs-index.mjs from each doc's frontmatter. Do not edit by hand: pnpm docs:index -->",
  "",
  "Start with [How Potyro works](00-how-potyro-works.md). The rest goes deeper, one subject per page.",
  "",
  "## Current",
  "",
  ...current.map(line),
  "",
  "## Historical",
  "",
  "Kept as records of a decision or a point in time. Each says at the top which current page replaces it.",
  "",
  ...historical.map(line),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let existing = "";
  try {
    existing = readFileSync(OUT, "utf8");
  } catch {}
  if (existing !== text) {
    console.error("docs/README.md is stale: run pnpm docs:index");
    process.exit(1);
  }
  console.log(`ok: docs/README.md lists ${docs.length} docs`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote docs/README.md (${current.length} current, ${historical.length} historical)`);
}
