#!/usr/bin/env node
// docs/README.md is generated from each doc's frontmatter, so the list of docs and what to trust
// cannot drift from the docs themselves.
//
//   node scripts/docs-index.mjs            write docs/README.md
//   node scripts/docs-index.mjs --check    exit 1 when it is stale or a doc has no frontmatter

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = join(ROOT, "docs");
const OUT = join(DOCS, "README.md");

/** The documentation's sections, in reading order, as the site publishes them (site/src/docs.mjs). */
const SECTIONS = [
  ["start", "Start"],
  ["concepts", "Concepts"],
  ["guides", "Guides"],
  ["reference", "Reference"],
  ["contributing", "Contributing"],
];
/** The engineering notes: kept in the repository, not published on the site. */
const NOTES = [
  ...readdirSync(DOCS).filter((n) => /^\d\d-.*\.md$|^handoff-.*\.md$/.test(n)),
  ...readdirSync(join(DOCS, "adr")).filter((n) => n.endsWith(".md")).map((n) => `adr/${n}`),
].sort();

function frontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(text);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^(\w+):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]] = kv[2].trim();
  }
  return out;
}

const missing = [];
const pages = [];
for (const [section] of SECTIONS) {
  const dir = join(DOCS, section);
  if (!existsSync(dir)) continue;
  for (const name of readdirSync(dir).filter((n) => n.endsWith(".md")).sort()) {
    const file = `${section}/${name}`;
    const fm = frontmatter(readFileSync(join(DOCS, file), "utf8"));
    if (!fm || !fm.title || !fm.description || fm.section !== section || fm.order === undefined) {
      missing.push(file);
      continue;
    }
    pages.push({ file, section, ...fm, order: Number(fm.order) });
  }
}
const notes = [];
for (const file of NOTES) {
  const fm = frontmatter(readFileSync(join(DOCS, file), "utf8"));
  if (!fm || !fm.title) {
    missing.push(file);
    continue;
  }
  // The owner's and the agents' working notes (`audience: owner`) stay in the private repository —
  // the public one is made without them (#115) — so the index the public reads does not name them.
  if (fm.audience === "owner") continue;
  notes.push({ file, ...fm });
}
if (missing.length) {
  for (const f of missing) console.error(`missing or incomplete frontmatter: docs/${f}`);
  process.exit(1);
}

const line = (d) => `- [${d.title}](${d.file}) — ${d.description ?? ""}`.trimEnd();
const text = [
  "# Potyro documentation",
  "",
  "<!-- Generated by scripts/docs-index.mjs from each page's frontmatter. Do not edit by hand: pnpm docs:index -->",
  "",
  "The documentation, as published at [potyro.com/docs](https://potyro.com/docs/). Start with",
  "[Introduction](start/introduction.md).",
  "",
  ...SECTIONS.flatMap(([id, label]) => {
    const items = pages.filter((p) => p.section === id).sort((a, b) => a.order - b.order || a.file.localeCompare(b.file));
    return items.length ? [`## ${label}`, "", ...items.map(line), ""] : [];
  }),
  "## Engineering notes",
  "",
  "The record of how Potyro was designed: decisions, measurements, prototypes. Kept for people",
  "changing Potyro, not maintained as user documentation, and not published on the site.",
  "",
  ...notes.map(line),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let existing = "";
  try {
    existing = readFileSync(OUT, "utf8");
  } catch {}
  if (existing !== text) {
    console.error("docs/README.md is stale: run pnpm docs:index");
    process.exit(1);
  }
  console.log(`ok: docs/README.md lists ${pages.length} pages and ${notes.length} notes`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote docs/README.md (${pages.length} pages, ${notes.length} notes)`);
}
